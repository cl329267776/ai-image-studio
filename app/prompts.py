PROMPTS_FILE = os.path.join(config.BASE_DIR, "prompts.json")


def load_prompts() -> dict:
    """读 prompts.json;不存在/损坏则用默认值并落盘"""
    if os.path.isfile(PROMPTS_FILE):
        try:
            with open(PROMPTS_FILE, encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, dict) and "main" in data and "detail" in data:
                return data
        except Exception:
            pass
    save_prompts(DEFAULT_PROMPTS)
    return DEFAULT_PROMPTS


def save_prompts(data: dict) -> None:
    """写 prompts.json(ensure_ascii=False 保留中文)"""
    with open(PROMPTS_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
